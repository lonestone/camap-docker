/**
 * Spec coverage report: which spec statements (task/refacto-hx-ts/specs) are
 * covered by a characterisation test, and which run under a known deviation.
 *
 *   npm run coverage:spec            -> tests/reports/spec-coverage.md
 *
 * Statements:  "- **XXX-YYY-NNN** ..." lines in specs/<NN-domain>/*.md.
 *              A statement is "undecided" if it says *Undecided (UND-NNN)* and
 *              "decided" if it carries a **DECISION (UND-NNN, ...)** line.
 * Tests:       tags of `playwright test --list --reporter=json` (@XXX-YYY-NNN),
 *              plus `deviation('UND-NNN')` calls found in the spec files.
 */
import { execFileSync } from 'node:child_process';
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { TESTS_ROOT, env } from '../src/env.js';

type Statement = {
  id: string;
  domain: string;
  file: string;
  title: string;
  undecided: string[];
  decided: string[];
};

const ID_RE = /^- \*\*([A-Z]{3}-[A-Z]{3}-\d{3})\*\*\s*(.*)$/;

function parseSpecs(dir: string): Statement[] {
  const out: Statement[] = [];
  for (const domain of readdirSync(dir).filter((d) => /^\d\d-/.test(d)).sort()) {
    for (const file of readdirSync(path.join(dir, domain)).filter((f) => f.endsWith('.md')).sort()) {
      let cur: Statement | undefined;
      for (const line of readFileSync(path.join(dir, domain, file), 'utf8').split('\n')) {
        const m = ID_RE.exec(line);
        if (m) {
          const title = m[2].replace(/<!--.*?-->/g, '').trim();
          cur = { id: m[1], domain, file: `${domain}/${file}`, title, undecided: [], decided: [] };
          for (const u of title.matchAll(/Undecided \((UND-\d+)\)/g)) cur.undecided.push(u[1]);
          out.push(cur);
          continue;
        }
        if (!cur) continue;
        if (/^- /.test(line) || /^#/.test(line)) {
          cur = undefined;
          continue;
        }
        for (const d of line.matchAll(/\*\*DECISION \((UND-\d+)/g)) if (!cur.decided.includes(d[1])) cur.decided.push(d[1]);
      }
    }
  }
  return out;
}

type ListedTest = { title: string; file: string; tags: string[]; project: string };

function listTests(): ListedTest[] {
  const json = execFileSync('npx', ['playwright', 'test', '--list', '--reporter=json'], {
    cwd: TESTS_ROOT,
    env: { ...process.env, TARGET: process.env.TARGET ?? 'hx' },
    encoding: 'utf8',
    maxBuffer: 64 * 1024 * 1024,
  });
  const report = JSON.parse(json.slice(json.indexOf('{')));
  const out: ListedTest[] = [];
  const walk = (suite: any, file: string) => {
    for (const spec of suite.specs ?? []) {
      for (const t of spec.tests ?? []) {
        out.push({ title: spec.title, file: spec.file ?? file, tags: spec.tags ?? [], project: t.projectName });
      }
    }
    for (const s of suite.suites ?? []) walk(s, s.file ?? file);
  };
  for (const s of report.suites ?? []) walk(s, s.file);
  return out;
}

function deviationsBySpecFile(): Map<string, string[]> {
  const m = new Map<string, string[]>();
  const root = path.join(TESTS_ROOT, 'specs');
  const visit = (dir: string) => {
    for (const e of readdirSync(dir, { withFileTypes: true })) {
      const p = path.join(dir, e.name);
      if (e.isDirectory()) visit(p);
      else if (e.name.endsWith('.spec.ts')) {
        const ids = [...readFileSync(p, 'utf8').matchAll(/deviation\(\s*['"]((?:UND|CODE)-\d+)['"]/g)].map((x) => x[1]);
        m.set(path.relative(TESTS_ROOT, p), [...new Set(ids)]);
      }
    }
  };
  visit(root);
  return m;
}

function main() {
  const statements = parseSpecs(env.specsDir);
  const known = new Set(statements.map((s) => s.id));
  const tests = listTests().filter((t) => t.project !== 'unit');
  const devs = deviationsBySpecFile();

  const coveredBy = new Map<string, ListedTest[]>();
  const unknownTags = new Set<string>();
  for (const t of tests) {
    for (const tag of t.tags) {
      const id = tag.replace(/^@/, '');
      if (!/^[A-Z]{3}-[A-Z]{3}-\d{3}$/.test(id)) continue;
      if (!known.has(id)) unknownTags.add(id);
      coveredBy.set(id, [...(coveredBy.get(id) ?? []), t]);
    }
  }

  const domains = [...new Set(statements.map((s) => s.domain))];
  const lines: string[] = [];
  const total = statements.length;
  const covered = statements.filter((s) => coveredBy.has(s.id));
  lines.push('# Spec coverage by characterisation tests', '');
  lines.push(`Generated by \`npm run coverage:spec\` (TARGET=${process.env.TARGET ?? 'hx'}). Do not edit.`, '');
  lines.push(`**${covered.length} / ${total}** statements covered (${((100 * covered.length) / total).toFixed(1)} %), by ${tests.length} tests.`, '');
  lines.push('| Domain | Statements | Covered | Undecided | Decided |', '|---|---:|---:|---:|---:|');
  for (const d of domains) {
    const ss = statements.filter((s) => s.domain === d);
    lines.push(
      `| ${d} | ${ss.length} | ${ss.filter((s) => coveredBy.has(s.id)).length} | ${ss.filter((s) => s.undecided.length).length} | ${ss.filter((s) => s.decided.length).length} |`,
    );
  }
  lines.push('', '## Covered statements', '', '| Statement | Spec | Tests | Deviations |', '|---|---|---|---|');
  for (const s of covered) {
    const ts = coveredBy.get(s.id)!;
    const files = [...new Set(ts.map((t) => t.file))];
    const dv = [...new Set(files.flatMap((f) => devs.get(f) ?? []))];
    lines.push(`| ${s.id} | ${s.file} | ${ts.map((t) => `${t.file}: ${t.title}`).join('<br>')} | ${dv.join(', ')} |`);
  }
  if (unknownTags.size) {
    lines.push('', '## Tags with no matching statement', '', ...[...unknownTags].map((t) => `- ${t}`));
  }
  lines.push('', '## Uncovered statements', '');
  for (const d of domains) {
    const ss = statements.filter((s) => s.domain === d && !coveredBy.has(s.id));
    if (!ss.length) continue;
    lines.push(`### ${d} (${ss.length})`, '');
    for (const s of ss) {
      const notes = [...s.undecided.map((u) => `undecided ${u}`), ...s.decided.map((u) => `decided ${u}`)];
      lines.push(`- ${s.id}${notes.length ? ` _(${notes.join(', ')})_` : ''}: ${s.title.slice(0, 140)}`);
    }
    lines.push('');
  }

  const outDir = path.join(TESTS_ROOT, 'reports');
  mkdirSync(outDir, { recursive: true });
  writeFileSync(path.join(outDir, 'spec-coverage.md'), lines.join('\n') + '\n');
  console.log(`spec coverage: ${covered.length}/${total} statements -> reports/spec-coverage.md`);
  if (unknownTags.size) console.warn(`unknown tags: ${[...unknownTags].join(', ')}`);
}

main();
