#!/usr/bin/env bash
# Regenerate tests/db/schema.sql, the schema baseline of the test DB (ROADBLOCKS C1).
#
# The schema is what TypeORM synchronises from the camap-ts entities (every hx
# table has an entity), dumped without data, plus the rows of `migrations` so
# that `typeorm migration:run` on this schema is a no-op. A production-derived
# dump can replace this file later without touching any test.
#
# Needs the nest-test image (stack.sh build). Starts mysql-test if needed,
# works in a scratch database, leaves camap_test untouched.
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd "$HERE/../.." && pwd)"
COMPOSE=(docker compose -f "$ROOT/docker-compose.test.yml")
OUT="$ROOT/tests/db/schema.sql"
DB=camap_baseline
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

mysql_exec() { "${COMPOSE[@]}" exec -T mysql-test mysql -uroot -proot --default-character-set=utf8mb4 "$@" 2>/dev/null; }

echo "[baseline] starting mysql-test"
mkdir -p "$ROOT/tests/.faketime"; [ -f "$ROOT/tests/db/schema.sql" ] || : > "$ROOT/tests/db/schema.sql"
[ -f "$ROOT/tests/db/seed.sql" ] || : > "$ROOT/tests/db/seed.sql"
"${COMPOSE[@]}" up -d mysql-test
until mysql_exec -e 'SELECT 1' >/dev/null; do sleep 2; done

echo "[baseline] fresh scratch database $DB"
mysql_exec -e "DROP DATABASE IF EXISTS $DB; CREATE DATABASE $DB CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;"

echo "[baseline] typeorm schema:sync from the camap-ts entities"
sed -E "s/^DB_DATABASE=.*/DB_DATABASE=$DB/" "$ROOT/tests/stack/nest.test.env" > "$TMP/baseline.env"
"${COMPOSE[@]}" run --rm --no-deps -T \
  -v "$TMP/baseline.env:/srv/.env:ro" \
  --entrypoint sh nest-test -c \
  'cd /srv/packages/api-core && node "$(node -p "require.resolve(\"typeorm/cli.js\")")" --config ormconfig.js schema:sync'

echo "[baseline] migrations rows"
{
  echo 'CREATE TABLE IF NOT EXISTS `migrations` (`id` int NOT NULL AUTO_INCREMENT, `timestamp` bigint NOT NULL, `name` varchar(255) NOT NULL, PRIMARY KEY (`id`)) ENGINE=InnoDB;'
  for f in "$ROOT"/camap-ts/packages/api-core/src/migrations/*.ts; do
    cls="$(grep -ho 'export class [A-Za-z0-9_]*' "$f" | head -1 | awk '{print $3}')"
    ts="$(echo "$cls" | grep -o '[0-9]\{13\}$')"
    echo "INSERT INTO migrations (timestamp, name) VALUES ($ts, '$cls');"
  done
} | mysql_exec "$DB"

echo "[baseline] dump -> tests/db/schema.sql"
DUMP=(mysqldump -uroot -proot --compact --skip-dump-date --set-gtid-purged=OFF --default-character-set=utf8mb4)
{
  echo "-- camap characterisation tests: schema baseline (ROADBLOCKS C1)."
  echo "-- GENERATED by tests/scripts/baseline-schema.sh from the camap-ts TypeORM entities"
  echo "-- (camap-ts $(git -C "$ROOT/camap-ts" rev-parse --short HEAD 2>/dev/null || echo '?')). Do not edit by hand."
  echo "SET NAMES utf8mb4;"
  echo "SET FOREIGN_KEY_CHECKS = 0;"
  echo
  "${COMPOSE[@]}" exec -T mysql-test "${DUMP[@]}" --no-data "$DB" 2>/dev/null | sed -E 's/ AUTO_INCREMENT=[0-9]+//'
  echo
  "${COMPOSE[@]}" exec -T mysql-test "${DUMP[@]}" --no-create-info --skip-extended-insert "$DB" migrations 2>/dev/null
  echo
  echo "SET FOREIGN_KEY_CHECKS = 1;"
} > "$OUT.tmp"
mv "$OUT.tmp" "$OUT"

mysql_exec -e "DROP DATABASE $DB;"
echo "[baseline] done: $(grep -c '^CREATE TABLE' "$OUT") tables"
echo "[baseline] restart the stack (stack.sh down && stack.sh up) to load it into camap_test"
